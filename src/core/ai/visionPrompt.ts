  "features": "高区分度特征数组(3-6项)。⚠️必须遵循排他性原则：只保留能将该款与同品类基础款区分开的视觉锚点。按优先级提取：①独特结构(抽绳/绑带/异形扣/开叉位置) ②标志性图案/IP/定位印花 ③特殊工艺(重工刺绣/扎染/磨破) ④辨识性廓形(茧型/A字/鱼尾)。❌过滤掉该品类的默认属性(如T恤的'圆领'、牛仔裤的'丹宁')，除非其形态异常",
