// src/core/nav.ts
// 侧栏**一级分组**定义（唯一出处）。
//
// 背景（2026-10-14）：侧栏原先是一级扁平列表（`enabledModuleMetas` 平铺），业务一多，
// "同一件事的多个面"就没有归处 —— 例如账号管理 / 企业主体 / 收件箱 / 店铺登记，
// 平铺成四个并列入口会让"它们属于同一件事"这层信息彻底丢失。
//
// 做法（最小分组能力，不引入中转页）：
//   · 本文件声明一级分组（id / 名称 / 图标 / 排序）；
//   · 模块在自己 meta 里写 `parent: '<groupId>'`；
//   · `AppShell.vue` 渲染"一级项 + 缩进子项"，子项本身仍是普通模块 ——
//     ⌘K 照常可搜、跨模块跳转照常可用、`navHidden` 语义不变。
//
// 两条硬约束：
//   1. **空分组不渲染**（没有子项的分组 = 点不动的死菜单）；
//   2. 子项的 `parent` 指向未登记的分组时，按"无分组"处理（入口不会凭这个字段消失）。
//
// ⚠️ 2026-10-14：「店铺管理」分组**撤销** —— 它唯一的子项「店铺账号管家」已整合为
//    一级入口「基础数据」（店铺账号 / 邮件 / 店铺登记 / 企业 / 供应商 / 成本与费率
//    六类资料收进同一个模块的左导航，见 `src/modules/shop-accounts/MasterDataView.vue`）。
//    分组留着就是一条点不动的死菜单（硬约束 1 会连它一起不渲染，但定义本身该删）。
//    分组机制本身保留：哪天又有一簇"同一件事的多个面"，照本文件头部三行做即可。
//
// ⚠️ 2026-10-17：又出现了一簇"同一件事的多个面"（「基础数据」的七类资料），但**没走本文件**。
//    判据：本文件的子项是**模块**（能独立激活、⌘K 可搜、跨模块跳转要记 TitleBar「返回」）；
//    七类资料不是 —— 它们是同一个模块的七个面，点了只换内容区、不换模块。
//    硬塞进 NAV_GROUPS 的后果是语义错位：⌘K 里出现七条"模块"、从发货台跳过去还会多一个「返回」。
//    ⇒ 那种情况用 `services/subNav.ts` 的**运行时上报**（`meta.subNav: true` + 模块 `reportSubNav`）。
//    一句话：**分组收模块，二级菜单收一个模块里的几个面。**
import type { ModuleIcon } from './types';

export interface NavGroup {
  /** 分组 id（模块 meta.parent 引用它） */
  id: string;
  /** 侧栏显示名 */
  name: string;
  icon?: ModuleIcon;
  /** 一级项排序（与模块 meta.order 同一坐标系） */
  order?: number;
}

export const NAV_GROUPS: NavGroup[] = [];
