/** 最长优先（`酒红` 必须压过 `红`）。词表是静态的，排序在模块加载时做一次。 */
const BY_LENGTH: ReadonlyArray<readonly [string, string]> = [...SWATCH_WORDS].sort(
  (a, b) => b[0].length - a[0].length
);

/**
 * 查询款色色块；**认不出返回 `null`**（界面不画色块）。
 *
 * 为什么不给中性灰兜底：灰色是一个"看起来像答案"的值 —— 人会以为这一行被设成了灰，
 * 实际只是名字不在字典里（`4` 号色、英文色名都会走到这里）。不画，比画错好。
 */
export function findSwatch(color: string): string | null {
  const c = String(color ?? '').trim().toLowerCase();
  if (!c) return null;
  for (const [name, value] of BY_LENGTH) {
    if (c.includes(name)) return value;
  }
  return null;
}
