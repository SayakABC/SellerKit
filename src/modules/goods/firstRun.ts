// 首次动线（2026-10-08 R3）：**空库一次性引导卡**的判据 + 那张卡与页头「?」共用的三步。
//
// 为什么判据要单独成一个纯函数（而不是写在模板的 v-if 里）：
// 它只有一行，但**两个数各有"不知道"这一态**，而"把 `null` 当 0"在这张页面上已经犯过一次
// （见 `docs/notes/2026-10-08-goods-page-entry-guide.md` 第 4 条：把 `null` 当 0，引导条会说出
// "都认完了"——那是它**不知道**的结论，代价是用户不再去配映射）。
// 纯函数 + 单测是唯一能让这条判断**可复现**的地方；写在模板里就只能靠真机看。

export interface FirstRunInput {
  /**
   * **全库**款数（来自 `productSummary.total`，**不受筛选影响**）；
   * `null` = 汇总还没拉到 —— 不是 0。
   *
   * ⚠️ 刻意不用列表的 `total`：那个是**按当前筛选**算出来的，用户开着"缺克重"筛选时
   * 它会等于 0，于是"零款"这个前提会被一个筛选条件伪造出来。
   */
  stylesTotal: number | null;
  /** 待关联队列聚合出的**组数**；`null` = 队列还没拉过 —— 同样不是 0 */
  queueGroups: number | null;
}

/**
 * 空库一次性引导卡该不该出现。
 *
 * 判据（审查报告 P0-6 原话）：`款数 === 0 且 队列已拉过且为空`（`null` 不算空）。
 *
 * 不重提常驻引导条：用户明确否过"步骤条"（2026-10-08 原话"感觉实用意义不大"）。
 * 这里只在**一个装完就没了的瞬间**出现 —— 一旦有了款、或订单进了队列，它自己就消失，
 * 所以它不占任何常驻高度，也不需要"我知道了"按钮（那种按钮只会制造一个查不出的持久状态）。
 */
export function shouldShowFirstRunCard(input: FirstRunInput): boolean {
  // 两个 `=== 0` 同时成立才出现：`null` 与 0 在这里是两个不同的意思（见上）。
  return input.stylesTotal === 0 && input.queueGroups === 0;
}

