// 「货与成本」的**术语词表**（唯一来源）。
//
// 2026-10-08 新手走查（方案 §1 · UX-G1）拍到的问题：这一页满屏行业词 ——
// 款 / SKU / 克重 / 映射 / 认款 / 店铺商品 / 关联率 —— **一个都没有解释**。
// 用户拍板的口径是「**保留术语 + 首次出现加括号**」，两条理由都记在这里：
//   · **不换词**：把「映射」说成"商品ID 与款的对应关系"会让老用户找不到熟悉的字眼，
//     而且和「发货台」页、算钱页的说法对不上（同一个东西三页三个叫法 = 又一种术语分裂）；
//   · **只在首次出现时补一句**，之后就照旧用术语 —— 每处都写一遍括号才是噪音。
//
// ⚠️ 括号里那句话必须**一个人能照着判断**。判据：没接触过电商的人读完能不能说出
//    "那我该先去干哪件事"。所以「款（产品）」这种写法绝对不行 —— 括号里又是个新词。
//    每条都写成"它是什么 + 它决定/影响什么"。
//
// ⚠️ 用 `gloss()` 而不是各文件自己拼括号：词表一旦有两份，就会出现"这页说'你自己定义的产品'、
//    那页说'自建商品'"这种漂移，而它长得不像 bug。
//
// ⚠️ 表里**只放真的用得到的词**（零消费者即删）：多备几个"以后可能用得上"的解释，
//    下一个人分不清哪几个是活的、哪几个是许愿池，改文案时还得逐个去搜。
export type GlossaryKey = 'style' | 'sku' | 'weight' | 'mapping' | 'relate';

/** 术语本身（正文里该用的那个词） */
export const TERM_LABEL: Record<GlossaryKey, string> = {
  style: '款',
  sku: 'SKU',
  weight: '克重',
  mapping: '映射',
  relate: '认款',
};

/** 首次出现时补在术语后面的那一句（**不加书名号、不引号，直接是括号内的正文**） */
export const GLOSSARY: Record<GlossaryKey, string> = {
  style: '你自己定义的产品，订单 / 采购 / 成本都挂在它上面',
  sku: '一个款下面的具体规格（如 黑 / L），克重是按 SKU 记的',
  weight: '单个 SKU 的重量（克），拣货单与运费都按它算',
  mapping: '店铺商品ID 与款之间的对应关系，配好之后订单才会自动归到款上',
  relate: '看着商品图判断它属于哪一款，然后把它认到那一款上',
};

/**
 * 术语 + 首次出现的括号说明。例：`gloss('style')` → `款（你自己定义的产品，…）`
 *
 * ⚠️ 全页**每个术语只用一次**。当前分工：
 *   · `style` / `sku` / `mapping` —— `GoodsView` 的页头说明（首屏那段唯一解释，见 `TAB_DESC`）；
 *   · `weight` —— 「编辑」抽屉的 SKU 子表（2026-10-09 起克重**只在那里编辑**，
 *     左栏展开区已把克重整块移走，只在说明里指一句"要改去点编辑"）；
 *   · `relate` —— 右栏队列空态（"还没有要认的商品"这句的说明位）。
 *   在第二处再写一遍括号 = 每次都解释一次，反而变成噪音。
 */
export function gloss(key: GlossaryKey): string {
  return `${TERM_LABEL[key]}（${GLOSSARY[key]}）`;
}
