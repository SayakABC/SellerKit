// 「货与成本」页签的**标识与显示名**（唯一来源）。
//
// 为什么单独一个文件：页签名是用户**真的点得到的入口名** —— 文案里写「去「货与成本」」
// 得能对上屏幕上真有的东西。名字只在这里写一遍、`GoodsView` 的页签表按 id 取它，
// 于是"改页签名"不会变成两处各写一遍然后悄悄漂开。
//
// ⚠️ 与 `src/modules/today/flowCtx.ts` 的 `SHIPPING_TAB_NAMES` 是**同类东西**，但两页的处置不同：
//    · 那边：悬空入口名守卫（`tests/uxEntryNames.spec.ts`）直接读它当**合法入口**（known）；
//    · 本页：页签名当前走那个测试文件里的 `ALLOWED_NON_ENTRY` 豁免 —— 判据是"用户已经在这一页上，
//      只是被指到同页另一个页签"。
//    ⭐ 但**豁免不等于那个入口存在**。所以存在性另有守卫，写在 `scripts/goods-ui-smoke.mjs`：
//      每个页签都要能点开、并渲染出**真的内容**（不是"页签在、点开一片空白"）。
//
// ── 2026-10-14「基础数据」整合后本页只剩两个页签 ────────────────────────────
// 「店铺登记 / 供应商 / 进价」三类资料**整体搬进「基础数据」模块**
// （`src/modules/shop-accounts/MasterDataView.vue` 的左导航），本页不再有这三个页签。
// 搬家的判据不是"这一页太长"，而是：维护动作散在三个模块里，用户为了记一家供应商
// 要先猜"它在哪个模块的第几个页签"；且「店名归一」原先在两个模块各有一份（两份实现，
// 改一处忘一处）。现在全类维护只有一个家。
// 原先指向这三个页签的行内出口（「现在登记」等）改为**跨模块跳转**
// （`switchModule('shop-accounts', <kind>)`），由 TitleBar 的「返回」送人回来。
