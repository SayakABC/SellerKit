/**
 * 页签 id → 用户可见名。
 * ⚠️ 四个 id 都在表里，但**同时出现在屏幕上的只有一部分**（页签表按页面形态分叉，见 `GoodsView`）：
 * `'workbench'` 形态 = 款与商品；`'tabs'` 回退形态 = 产品 /（商品清单）/ 映射与关联。
 * 所以**别拿这张表当"页签都在"的判据**。
 *
 * ── 2026-10-25 改名：`建档与关联` → `款与商品`（用户口径「这几个字不合适」）──
 * 判据不是"顺不顺口"，是**名字的语法形态与它所在的那一层不匹配**：
 *   · 侧栏读作「产品管理 › <名>」—— 组名是名词，项名却是**两个动词并列**（建档 + 关联），
 *     读起来像一条待办，不像"这一类资料叫什么"；同组的「供应商」是名词，两者不对称；
 *   · 它也没覆盖这一屏真正的内容：左边是款档案，右边是**店铺商品**。名字里只有"建档"与"关联"
 *     两个动作，用户看到的是两个对象。
 * 新名字与两栏一一对应（左 = 款，右 = 商品），"建档 / 认款"两个动作都被它覆盖。
 * 备选与不选的理由：`认款台`（与「发货台」同构，但弱化了左栏的档案维护）、
 *   `产品库`（与组名「产品管理」重复"产品"，读作「产品管理 › 产品库」）。
 * ⚠️ 改的只有**呈现名**：`store.mainTab` 的值仍是 `'goods'`，跨模块 action 的字符串协议没变
 *   ⇒ 用户本地偏好与「待补清单 / 归类核对」里的跳转全部照旧可用。
 */
