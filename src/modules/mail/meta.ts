import type { ModuleMeta } from '@/core/types';

// 「邮件」：一级入口（2026-10-17 从「基础数据」左导航的第二项独立出来）。
//
// 为什么独立：收件箱不是"维护一份资料"，它有自己的动线 —— 进来就是读 / 筛 / 同步 / 清缓存，
//   与「把这家店、这家厂、这个价记下来」那类动作不是一回事。放在「基础数据」里时，
//   用户要读一封信得先想到"它属于哪一类资料"，而它恰恰是最需要**一步到位**的东西
//   （未读邮件是每天都要看的，不是偶尔维护的）。
// 判据与 2026-10-14 那次整合相反的吗？不是。那次整合的是**同一类动作**（维护），
//   这次拆出来的是**另一类动作**（读信）。"同一件事只留一个入口"仍然成立：
//   邮件此后只有这一个入口，账号库里的「邮箱接入」是**账号的属性**（绑定/解绑），不是收件箱的第二个入口。
//
// 模块 id 仍是 `mail`，但**持久化命名空间刻意沿用 `shop-accounts-mail`**（见 `mailStore.ts` 头注释）：
//   模块 id 是路由/构建键，存储键是历史包袱 —— 一起改等于让老用户的本地缓存凭空失踪。
export const meta: ModuleMeta = {
  id: 'mail',
  name: '邮件',
  icon: 'inbox',
  // 排序：发货台(1) → 基础数据(2) → 邮件(3) → 统计(4) → 便签(6)。
  // 「货与成本」并入基础数据后空出的第 3 位给邮件：读信与维护资料是同一层的高频事，
  // 都排在业务页（统计）之前。⚠️ 第 5 位原属「拣货」，2026-10-17 该入口摘掉（清单在「今天 › 拿货」里），
  // 位号不复用 —— 排序是相对值，补空位只会让后来人以为"这里还有东西"。
  order: 3,
};
